#[derive(Deserialize)]
pub struct IntegratorConfig {
    pub api_key: String,
    pub name: String,
    pub quota: u64,
}

pub struct Config {
    pub environment: Environment,
    pub rpc_url: String,
    pub ws_url: String,
    pub relayer_keypair: Keypair,
    pub sas_authority_keypair: Option<Keypair>,
    pub listen_addr: SocketAddr,
    pub api_keys: Vec<String>,
    pub rate_limit_per_minute: u32,
    pub study_rate_limit_per_minute: u32,
    pub study_max_in_flight: usize,
    /// Per-IP request cap across wallets and API keys.
    /// Railway supplies the client address through `X-Real-IP`.
    pub per_ip_rate_limit_per_minute: u32,
    pub integrators: Vec<IntegratorConfig>,
    pub cors_origins: Vec<HeaderValue>,
    pub sas_credential_pda: Option<Pubkey>,
    pub sas_schema_pda: Option<Pubkey>,
    pub sas_attestation_ttl_days: u64,
    pub validation_service_url: Option<String>,
    /// Ed25519 signature (bs58-encoded) over `Entros-VALIDATOR-URL-V1:<url>`
    /// signed by the protocol authority. Verified against
    /// `VALIDATION_URL_AUTHORITY_BS58` on startup when `ENVIRONMENT=prod`.
    pub validation_service_url_signature: Option<String>,
    pub validation_api_key: Option<String>,
    pub challenge_ttl_secs: u64,
    /// Per-wallet validation-attempt cap. Soft cap on
    /// the number of attempts a single wallet can make in the configured
    /// window before being rate-limited. Successful attempts refund their
    /// slot; only failures persist against the cap. Configurable via
    /// `VALIDATION_WALLET_MAX_ATTEMPTS`. Default 5 — permissive enough
    /// for legit users with borderline mics / accents to retry, tight
    /// enough to bound per-wallet retry damage.
    pub wallet_max_attempts: u8,
    /// Sliding-window length for `wallet_max_attempts`. Configurable via
    /// `VALIDATION_WALLET_WINDOW_SECS`. Default 3600 (1 hour).
    pub wallet_window_secs: u64,
    /// Observe-only automation-detection logging.
    /// When true, the `/validate-features` handler logs the client-collected
    /// automation signal for calibration — it never affects the verification
    /// decision either way. Configurable via `EXECUTOR_AUTOMATION_OBSERVE`.
    /// Default true (observe-first).
    pub automation_observe: bool,
    /// Automation hard gate. When true, a request reporting
    /// navigator.webdriver === true is rejected outright (prod only — no effect
    /// on the dev pass-through with no validator configured). Disable for the
    /// team's own E2E automation via `EXECUTOR_AUTOMATION_WEBDRIVER_REJECT`.
    /// Default true. Client-reported, so it stops lazy automation, not a
    /// determined attacker who hides the flag — the biometric pipeline is the
    /// backstop.
    pub automation_webdriver_reject: bool,
    /// Observe-only wallet-reputation logging.
    /// When true, the `/validate-features` handler reads the verifying wallet's
    /// public on-chain reputation (balance + recent activity) in a detached task
    /// and logs it for calibration — it never affects the verification decision,
    /// quota, or latency. Configurable via `EXECUTOR_WALLET_REPUTATION_OBSERVE`.
    /// Default true (observe-first).
    pub wallet_reputation_observe: bool,
    /// Observe-only curve-trace region/kinematics logging (touch-curve Stage 1).
    /// When true, `/validate-features` scores the client's coarse curve-trace
    /// outline against the issued curve (region proximity + gesture speed/nature)
    /// and logs it for calibration — it never affects the verification decision.
    /// Configurable via `EXECUTOR_CURVE_TRACE_OBSERVE`. Default true (observe-first).
    pub curve_trace_observe: bool,
    /// Cross-wallet verification cooldown duration in seconds.
    /// Configurable via `VALIDATION_CROSS_WALLET_COOLDOWN_SECS`. Default 86400 (24h).
    pub cross_wallet_cooldown_secs: u64,
    /// Enforces cross-wallet cooldown blocks when true. When false, overlaps are
    /// logged but verification proceeds. Configurable via `VALIDATION_CROSS_WALLET_COOLDOWN_ENFORCE`.
    /// Default false (observe-only for NAT/shared-network safety).
    pub cross_wallet_cooldown_enforce: bool,
    pub scoring_config: ResolvedScoringConfig,
}

impl Config {
    pub fn from_env() -> Result<Self, Box<dyn std::error::Error>> {
        let environment = Environment::parse(std::env::var("ENVIRONMENT").ok().as_deref())?;
        if !cfg!(debug_assertions) && !environment.is_prod() {
            return Err("release builds require ENVIRONMENT=prod".into());
        }

        let scoring_bundle = std::env::var(SCORING_CONFIG_ENV_VAR).ok();
        let development_fallback =
            cfg!(debug_assertions) && !environment.is_prod() && scoring_bundle.is_none();
        let scoring_authority = match SCORING_CONFIG_AUTHORITY_BS58 {
            Some(value) => Pubkey::from_str(value)
                .map_err(|_| "compiled scoring authority is not a valid public key")?,
            None if development_fallback => Pubkey::default(),
            None => return Err("this build has no configured scoring authority".into()),
        };
        let scoring_config_id = match SCORING_CONFIG_ID_BS58 {
            Some(value) => ScoringConfigId::parse_compiled(value)?,
            None if development_fallback => ScoringConfigId("development-default".into()),
            None => return Err("this build has no pinned scoring config ID".into()),
        };
        let scoring_config = resolve_scoring_config(
            scoring_bundle.as_deref(),
            &ScoringConfigRequirements {
                authority: scoring_authority,
                config_id: scoring_config_id,
                service: EXPECTED_SCORING_SERVICE,
                cluster: ScoringCluster::Devnet,
                environment,
                revision: EXPECTED_SCORING_CONFIG_REVISION,
            },
        )?;

        let rpc_url =
            std::env::var("RPC_URL").unwrap_or_else(|_| "https://api.devnet.solana.com".into());

        let ws_url =
            std::env::var("WS_URL").unwrap_or_else(|_| "wss://api.devnet.solana.com".into());

        let relayer_keypair = if let Ok(json) = std::env::var("RELAYER_KEYPAIR") {
            let bytes: Vec<u8> = serde_json::from_str(&json)
                .map_err(|e| format!("RELAYER_KEYPAIR is not valid JSON: {e}"))?;
            Keypair::try_from(bytes.as_slice())
                .map_err(|e| format!("RELAYER_KEYPAIR contains invalid keypair: {e}"))?
        } else {
            let keypair_path = std::env::var("RELAYER_KEYPAIR_PATH")
                .unwrap_or_else(|_| "./relayer-keypair.json".into());
            read_keypair_file(&keypair_path)
                .map_err(|e| format!("Failed to read keypair from {keypair_path}: {e}"))?
        };

        let listen_addr: SocketAddr = if let Ok(port) = std::env::var("PORT") {
            format!("0.0.0.0:{port}").parse()?
        } else {
            std::env::var("LISTEN_ADDR")
                .unwrap_or_else(|_| "0.0.0.0:3001".into())
                .parse()?
        };

        let api_keys: Vec<String> = match std::env::var("API_KEYS") {
            Ok(s) => serde_json::from_str(&s)
                .map_err(|e| format!("API_KEYS contains invalid JSON: {e}"))?,
            Err(_) => vec![],
        };

        let rate_limit_per_minute: u32 = match std::env::var("RATE_LIMIT_PER_MINUTE") {
            Ok(s) => s
                .parse()
                .map_err(|e| format!("RATE_LIMIT_PER_MINUTE is not a valid u32: {e}"))?,
            Err(_) => 60,
        };

        let study_rate_limit_per_minute: u32 = match std::env::var("STUDY_RATE_LIMIT_PER_MINUTE") {
            Ok(s) => s
                .parse()
                .map_err(|e| format!("STUDY_RATE_LIMIT_PER_MINUTE is not a valid u32: {e}"))?,
            Err(_) => 600,
        };
        if !(1..=10_000).contains(&study_rate_limit_per_minute) {
            return Err("STUDY_RATE_LIMIT_PER_MINUTE must be between 1 and 10000".into());
        }

        let study_max_in_flight: usize = match std::env::var("STUDY_MAX_IN_FLIGHT") {
            Ok(s) => s
                .parse()
                .map_err(|e| format!("STUDY_MAX_IN_FLIGHT is not a valid usize: {e}"))?,
            Err(_) => 32,
        };
        if !(1..=256).contains(&study_max_in_flight) {
            return Err("STUDY_MAX_IN_FLIGHT must be between 1 and 256".into());
        }

        let per_ip_rate_limit_per_minute: u32 =
            match std::env::var("EXECUTOR_PER_IP_RATE_LIMIT_PER_MIN") {
                Ok(s) => s.parse().map_err(|e| {
                    format!("EXECUTOR_PER_IP_RATE_LIMIT_PER_MIN is not a valid u32: {e}")
                })?,
                Err(_) => 30,
            };

        let integrators: Vec<IntegratorConfig> = match std::env::var("INTEGRATORS") {
            Ok(s) => serde_json::from_str(&s)
                .map_err(|e| format!("INTEGRATORS contains invalid JSON: {e}"))?,
            Err(_) => vec![],
        };

        let api_keys = if api_keys.is_empty() && !integrators.is_empty() {
            integrators.iter().map(|i| i.api_key.clone()).collect()
        } else {
            api_keys
        };

        let cors_origin_values: Vec<String> = match std::env::var("CORS_ORIGINS") {
            Ok(s) => serde_json::from_str(&s)
                .map_err(|e| format!("CORS_ORIGINS contains invalid JSON: {e}"))?,
            Err(_) => vec![],
        };
        let cors_origins = parse_cors_origins(cors_origin_values, environment)?;

        let sas_authority_keypair = if let Ok(json) = std::env::var("SAS_AUTHORITY_KEYPAIR") {
            let bytes: Vec<u8> = serde_json::from_str(&json)
                .map_err(|e| format!("SAS_AUTHORITY_KEYPAIR is not valid JSON: {e}"))?;
            Some(
                Keypair::try_from(bytes.as_slice())
                    .map_err(|e| format!("SAS_AUTHORITY_KEYPAIR contains invalid keypair: {e}"))?,
            )
        } else if let Ok(path) = std::env::var("SAS_AUTHORITY_KEYPAIR_PATH") {
            Some(
                read_keypair_file(&path).map_err(|e| {
                    format!("Failed to read SAS authority keypair from {path}: {e}")
                })?,
            )
        } else {
            None
        };

        let sas_credential_pda = std::env::var("SAS_CREDENTIAL_PDA")
            .ok()
            .and_then(|s| Pubkey::from_str(&s).ok());

        let sas_schema_pda = std::env::var("SAS_SCHEMA_PDA")
            .ok()
            .and_then(|s| Pubkey::from_str(&s).ok());

        let sas_attestation_ttl_days: u64 = std::env::var("SAS_ATTESTATION_TTL_DAYS")
            .ok()
            .and_then(|s| s.parse().ok())
            .unwrap_or(30);

        let validation_service_url = std::env::var("VALIDATION_SERVICE_URL").ok();
        let validation_service_url_signature =
            std::env::var("VALIDATION_SERVICE_URL_SIGNATURE").ok();
        let validation_api_key = std::env::var("VALIDATION_API_KEY").ok();

        let challenge_ttl_secs: u64 = std::env::var("CHALLENGE_TTL_SECS")
            .ok()
            .and_then(|s| s.parse().ok())
            .unwrap_or(60);

        // Default 5 attempts / 1h. Permissive at launch — tightenable
        // via env var once we have real-user failure-rate data.
        let wallet_max_attempts: u8 = std::env::var("VALIDATION_WALLET_MAX_ATTEMPTS")
            .ok()
            .and_then(|s| s.parse().ok())
            .unwrap_or(5);

        let wallet_window_secs: u64 = std::env::var("VALIDATION_WALLET_WINDOW_SECS")
            .ok()
            .and_then(|s| s.parse().ok())
            .unwrap_or(3600);

        // Observe-first: both default ON so we collect calibration data as soon
        // as SDKs/traffic provide the signal. Set `=false` (or `0`/`no`/`off`)
        // to silence. An unrecognized value KEEPS the default rather than
        // silently disabling the signal on a typo; resolved values are logged at
        // startup in main.rs.
        let automation_observe = parse_bool_env("EXECUTOR_AUTOMATION_OBSERVE", true);
        let automation_webdriver_reject =
            parse_bool_env("EXECUTOR_AUTOMATION_WEBDRIVER_REJECT", true);
        let wallet_reputation_observe = parse_bool_env("EXECUTOR_WALLET_REPUTATION_OBSERVE", true);
        let curve_trace_observe = parse_bool_env("EXECUTOR_CURVE_TRACE_OBSERVE", true);

        let cross_wallet_cooldown_secs: u64 =
            std::env::var("VALIDATION_CROSS_WALLET_COOLDOWN_SECS")
                .ok()
                .and_then(|s| s.parse().ok())
                .unwrap_or(86400);

        let cross_wallet_cooldown_enforce =
            parse_bool_env("VALIDATION_CROSS_WALLET_COOLDOWN_ENFORCE", false);

        Ok(Config {
            environment,
            rpc_url,
            ws_url,
            relayer_keypair,
            sas_authority_keypair,
            listen_addr,
            api_keys,
            rate_limit_per_minute,
            study_rate_limit_per_minute,
            study_max_in_flight,
            per_ip_rate_limit_per_minute,
            integrators,
            cors_origins,
            sas_credential_pda,
            sas_schema_pda,
            sas_attestation_ttl_days,
            validation_service_url,
            validation_service_url_signature,
            validation_api_key,
            challenge_ttl_secs,
            wallet_max_attempts,
            wallet_window_secs,
            automation_observe,
            automation_webdriver_reject,
            wallet_reputation_observe,
            curve_trace_observe,
            cross_wallet_cooldown_secs,
            cross_wallet_cooldown_enforce,
            scoring_config,
        })
    }
}
