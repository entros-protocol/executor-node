#[derive(Clone, Copy, Debug, Eq, PartialEq)]
#[repr(u8)]
pub(crate) enum ScoringCluster {
    Devnet = 1,
}

impl ScoringCluster {
    const fn code(self) -> u8 {
        self as u8
    }
}

/// Fixed-width signed payload. Integer parts per million avoid float encoding
/// differences between the Rust verifier and the offline signing tool.
#[derive(BorshDeserialize, BorshSerialize)]
struct SignedScoringPayload {
    schema_version: u8,
    service: [u8; 16],
    cluster: u8,
    environment: u8,
    revision: u64,
    audit_nonce: [u8; 32],
    biometric_ppm: u32,
    tts_ppm: u32,
    unallocated_ppm: u32,
    automation_ppm: u32,
    reputation_ppm: u32,
    friction_threshold_ppm: u32,
    reject_threshold_ppm: u32,
}

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub(crate) enum ScoringConfigSource {
    DevelopmentDefault,
    Signed,
}

/// Opaque identifier safe for startup logs. The signed payload contains a
/// nonce generated by the signing tool, so this digest does not expose the
/// low-entropy policy values.
#[derive(Clone, Debug, Eq, PartialEq)]
pub(crate) struct ScoringConfigId(String);

impl ScoringConfigId {
    pub(crate) fn as_str(&self) -> &str {
        &self.0
    }

    fn parse_compiled(value: &str) -> Result<Self, String> {
        let decoded = bs58::decode(value)
            .into_vec()
            .map_err(|_| "compiled scoring config ID is not valid base58".to_string())?;
        if decoded.len() != 32 || bs58::encode(decoded).into_string() != value {
            return Err("compiled scoring config ID is not a canonical 32-byte value".to_string());
        }
        Ok(Self(value.to_string()))
    }
}

#[derive(Debug)]
pub(crate) struct ResolvedScoringConfig {
    pub(crate) config: ScoringConfig,
    pub(crate) revision: u64,
    pub(crate) config_id: ScoringConfigId,
    pub(crate) source: ScoringConfigSource,
}

pub(crate) struct ScoringConfigRequirements {
    pub(crate) authority: Pubkey,
    pub(crate) config_id: ScoringConfigId,
    pub(crate) service: [u8; 16],
    pub(crate) cluster: ScoringCluster,
    pub(crate) environment: Environment,
    pub(crate) revision: u64,
}

/// Resolve the configured scoring policy without reading process state.
/// Production always requires a signed bundle. Development may use the neutral
/// public default only when no bundle was supplied.
pub(crate) fn resolve_scoring_config(
    bundle: Option<&str>,
    requirements: &ScoringConfigRequirements,
) -> Result<ResolvedScoringConfig, String> {
    let Some(bundle) = bundle else {
        if requirements.environment.is_prod() {
            return Err(format!(
                "{SCORING_CONFIG_ENV_VAR} is required when ENVIRONMENT=prod"
            ));
        }
        return Ok(ResolvedScoringConfig {
            config: ScoringConfig::development_default(),
            revision: 0,
            config_id: ScoringConfigId("development-default".into()),
            source: ScoringConfigSource::DevelopmentDefault,
        });
    };

    if bundle.len() > SCORING_CONFIG_BUNDLE_MAX_BYTES {
        return Err(format!(
            "{SCORING_CONFIG_ENV_VAR} exceeds the maximum encoded size"
        ));
    }
    if !bundle.is_ascii() {
        return Err(format!(
            "{SCORING_CONFIG_ENV_VAR} must contain ASCII base58 data"
        ));
    }

    let mut parts = bundle.split('.');
    let payload_bs58 = parts.next().unwrap_or_default();
    let signature_bs58 = parts
        .next()
        .ok_or_else(|| format!("{SCORING_CONFIG_ENV_VAR} must contain payload.signature"))?;
    if payload_bs58.is_empty() || signature_bs58.is_empty() || parts.next().is_some() {
        return Err(format!(
            "{SCORING_CONFIG_ENV_VAR} must contain exactly one payload.signature pair"
        ));
    }

    let payload_bytes = decode_canonical_base58(payload_bs58, "payload")?;
    if payload_bytes.len() != SCORING_CONFIG_PAYLOAD_BYTES {
        return Err(format!(
            "{SCORING_CONFIG_ENV_VAR} payload has an invalid length"
        ));
    }
    let signature_bytes = decode_canonical_base58(signature_bs58, "signature")?;
    let signature = Signature::try_from(signature_bytes.as_slice())
        .map_err(|_| format!("{SCORING_CONFIG_ENV_VAR} signature has an invalid length"))?;

    let mut signed_message = Vec::with_capacity(SCORING_CONFIG_DOMAIN.len() + payload_bytes.len());
    signed_message.extend_from_slice(SCORING_CONFIG_DOMAIN);
    signed_message.extend_from_slice(&payload_bytes);
    if !signature.verify(requirements.authority.as_ref(), &signed_message) {
        return Err(format!(
            "{SCORING_CONFIG_ENV_VAR} signature does not verify against the scoring authority"
        ));
    }

    let payload: SignedScoringPayload = borsh::from_slice(&payload_bytes)
        .map_err(|_| format!("{SCORING_CONFIG_ENV_VAR} payload is malformed"))?;
    validate_scoring_binding(&payload, requirements)?;

    if payload.audit_nonce.iter().all(|byte| *byte == 0) {
        return Err(format!(
            "{SCORING_CONFIG_ENV_VAR} audit nonce must not be all zeroes"
        ));
    }

    let config = ScoringConfig::try_new(
        payload.biometric_ppm,
        payload.tts_ppm,
        payload.unallocated_ppm,
        payload.automation_ppm,
        payload.reputation_ppm,
        payload.friction_threshold_ppm,
        payload.reject_threshold_ppm,
    )
    .map_err(|_| format!("{SCORING_CONFIG_ENV_VAR} policy invariants are invalid"))?;

    let config_id = ScoringConfigId(hashv(&[SCORING_CONFIG_DOMAIN, &payload_bytes]).to_string());
    if config_id != requirements.config_id {
        return Err(format!(
            "{SCORING_CONFIG_ENV_VAR} config ID does not match this release"
        ));
    }

    Ok(ResolvedScoringConfig {
        config,
        revision: payload.revision,
        config_id,
        source: ScoringConfigSource::Signed,
    })
}

fn decode_canonical_base58(value: &str, field: &str) -> Result<Vec<u8>, String> {
    let decoded = bs58::decode(value)
        .into_vec()
        .map_err(|_| format!("{SCORING_CONFIG_ENV_VAR} {field} is not valid base58"))?;
    if bs58::encode(&decoded).into_string() != value {
        return Err(format!(
            "{SCORING_CONFIG_ENV_VAR} {field} must use canonical base58"
        ));
    }
    Ok(decoded)
}

fn validate_scoring_binding(
    payload: &SignedScoringPayload,
    requirements: &ScoringConfigRequirements,
) -> Result<(), String> {
    if payload.schema_version != SCORING_CONFIG_SCHEMA_VERSION {
        return Err(format!(
            "{SCORING_CONFIG_ENV_VAR} schema version is not supported"
        ));
    }
    if payload.service != requirements.service {
        return Err(format!(
            "{SCORING_CONFIG_ENV_VAR} service binding does not match"
        ));
    }
    if payload.cluster != requirements.cluster.code() {
        return Err(format!(
            "{SCORING_CONFIG_ENV_VAR} cluster binding does not match"
        ));
    }
    if payload.environment != requirements.environment.scoring_code() {
        return Err(format!(
            "{SCORING_CONFIG_ENV_VAR} environment binding does not match"
        ));
    }
    if payload.revision != requirements.revision {
        return Err(format!(
            "{SCORING_CONFIG_ENV_VAR} revision binding does not match"
        ));
    }
    Ok(())
}

/// Read a boolean env var with lenient truthy/falsy spellings. An unset or
/// unrecognized value returns `default`, so a typo never silently flips an
/// observe-first flag off.
fn parse_bool_env(key: &str, default: bool) -> bool {
    parse_bool(std::env::var(key).ok().as_deref(), default)
}

/// Pure core of [`parse_bool_env`], split out so the spelling rules are unit
/// testable without touching process env.
fn parse_bool(value: Option<&str>, default: bool) -> bool {
    match value {
        None => default,
        Some(s) => match s.trim().to_ascii_lowercase().as_str() {
            "1" | "true" | "yes" | "on" => true,
            "0" | "false" | "no" | "off" => false,
            _ => default,
        },
    }
}

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum Environment {
    Dev,
    Prod,
}

impl Environment {
    fn parse(value: Option<&str>) -> Result<Self, String> {
        match value.unwrap_or("dev") {
            "dev" => Ok(Self::Dev),
            "prod" => Ok(Self::Prod),
            other => Err(format!(
                "ENVIRONMENT must be either dev or prod, got {other:?}"
            )),
        }
    }

    pub fn is_prod(self) -> bool {
        self == Self::Prod
    }

    const fn scoring_code(self) -> u8 {
        match self {
            Self::Dev => 1,
            Self::Prod => 2,
        }
    }
}

fn parse_cors_origins(
    values: Vec<String>,
    environment: Environment,
) -> Result<Vec<HeaderValue>, String> {
    if environment.is_prod() && values.is_empty() {
        return Err("CORS_ORIGINS must contain at least one origin when ENVIRONMENT=prod".into());
    }

    values
        .into_iter()
        .map(|value| {
            let uri: Uri = value
                .parse()
                .map_err(|_| format!("CORS_ORIGINS contains an invalid origin: {value:?}"))?;
            let valid_scheme = matches!(uri.scheme_str(), Some("http" | "https"));
            let valid_path = uri.path() == "/" && uri.query().is_none();
            if !valid_scheme || uri.authority().is_none() || !valid_path {
                return Err(format!(
                    "CORS_ORIGINS entries must be HTTP origins without paths: {value:?}"
                ));
            }
            HeaderValue::from_str(&value)
                .map_err(|_| format!("CORS_ORIGINS contains an invalid header value: {value:?}"))
        })
        .collect()
}

